// Normalize game name for better matching
const normalizeGameName = (name) => {
  if (typeof name !== 'string') {
    return '';
  }

  return name
    .toLowerCase()
    .trim()
    // Remove special characters and symbols
    .replace(/[®™©]/g, '')
    .replace(/[:\-–—]/g, ' ')
    .replace(/['']/g, "'")
    // Remove edition suffixes
    .replace(/\s+(goty|game of the year|deluxe|ultimate|gold|premium|complete|definitive|enhanced|remastered|remake|special|collectors?|limited|standard|digital)\s*(edition)?$/i, '')
    // Remove year suffixes
    .replace(/\s+\(\d{4}\)$/, '')
    .replace(/\s+\d{4}$/, '')
    // Normalize whitespace
    .replace(/\s+/g, ' ')
    .trim();
};

// Helper function to check if a game belongs to a genre
export const gameBelongsToGenre = (gameName, genre) => {
  const normalizedGameName = normalizeGameName(gameName);
  if (!normalizedGameName) {
    return false;
  }

  const resolvedGenre = Object.keys(gameGenreDatabase).find(
    (databaseGenre) => databaseGenre.toLowerCase() === String(genre || '').toLowerCase()
  );
  if (!resolvedGenre) {
    return false;
  }
  
  return gameGenreDatabase[resolvedGenre].some(game => {
    const normalizedDatabaseGame = normalizeGameName(game);
    
    // Exact match first
    if (normalizedDatabaseGame === normalizedGameName) {
      return true;
    }
    
    // Check if database game contains the full game name (for variations)
    if (normalizedDatabaseGame.includes(normalizedGameName)) {
      return true;
    }
    
    // Check if game name contains the full database game name
    if (normalizedGameName.includes(normalizedDatabaseGame)) {
      return true;
    }
    
    // Check for core title match (first 3+ words)
    const gameWords = normalizedGameName.split(' ').filter(w => w.length > 2);
    const dbWords = normalizedDatabaseGame.split(' ').filter(w => w.length > 2);
    
    if (gameWords.length >= 2 && dbWords.length >= 2) {
      const coreGame = gameWords.slice(0, Math.min(3, gameWords.length)).join(' ');
      const coreDb = dbWords.slice(0, Math.min(3, dbWords.length)).join(' ');
      
      if (coreGame === coreDb && coreGame.length > 5) {
        return true;
      }
    }
    
    return false;
  });
};

